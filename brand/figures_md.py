"""Write brand/FIGURES.md, "How these figures were made", from the committed snapshots.

    python brand/figures_md.py [--frontier brand/data/frontier.json] [--concurrency brand/data/concurrency.json]
                               [--di brand/data/di.json]

The figures keep only what a reader needs to read them; everything else about how they were measured (builds, GiB,
each arm's runtime and timer, the seed, callo compare's flags, the S1-fallback case in full, the README's limit, the
run-to-run floor, the gaps) is here, generated from the same snapshots so it cannot drift from the figures. The builds
are named by role throughout; their commits, which are of callo's development history and not published, are listed
once at the end (from `data/builds.json`), with the commit each snapshot was built at.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent

INTRO = """# How these figures were made

Generated by `brand/figures_md.py` from `brand/data/frontier.json`, `brand/data/concurrency.json` and
`brand/data/di.json` (Callo's builds from `brand/data/builds.json`); do not edit by hand. The figures themselves carry
only what is needed to read them; this page holds the rest.

Rebuild (no GPU, no model server). The PNGs were rendered with Playwright 1.63.0 (its Chromium 1243); a newer
Playwright wants a newer Chromium build. Each `build` reads the benchmark's results under `--root` (`<bench>`, the
benchmark harness's checkout, which is not published) and records every source relative to it; `draw`, this page and
the tests need only the committed snapshots (the real-data tests run when `CALLO_BENCH_ROOT` and `CALLO_PLATE_RESULTS`
point at the results, and skip otherwise).

```sh
R="uv run --with fonttools --with uharfbuzz --with pillow --with playwright==1.63.0"
$R python brand/frontier.py build --spec brand/data/frontier.release.spec.json --root <bench>/harness/results/callo_v0.3
$R python brand/frontier.py draw --png [--latency p50|p95]   # -> brand/frontier-{dark,light}[-stat].svg / @2x.png
$R python brand/concurrency.py build --src <bench>/harness/results/callo_v0.3/plate/concurrency.json --root <bench>
$R python brand/concurrency.py draw --png                    # -> brand/concurrency-{dark,light}.svg / @2x.png
$R python brand/di.py build --spec brand/data/di.release.spec.json --root <bench>
$R python brand/di.py draw --png         # -> brand/di-{dark,light}.svg, brand/di-chart-{dark,light}.svg / @2x.png
$R python brand/figures_md.py                                # -> brand/FIGURES.md
CALLO_BENCH_ROOT=<bench> CALLO_PLATE_RESULTS=<bench>/harness/results/callo_v0.3 $R pytest brand/tests
```
"""

PLATE_METHOD = """## The release plate (`frontier.py`)

Accuracy against per-decision latency on the same test items, Callo's thinking budgets beside trained decision heads.
Every statistic is Callo's own code, never a copy: `compare.load_profile` / `refusals` / `pairing` / `points_of` /
`rows_at` / `joint` and `think.frontier` / `latency_stats` / `paired_bootstrap`, with one seed, one row set and one
source stratification, exactly as `callo compare`. Only thinking-budget points are plotted: a profile's early-exit
points are opt-in and never picked, so they are listed below, not drawn. A rows arm (a trained head, a quantized
Clef) is refused unless it covers every paired question, carries no error row and was measured on the same data.
Inputs are named by file and sha256.
"""

DI_METHOD = """## The Decision Index plate (`di.py`)

The headline release figure: the Decision Index 0.3 public subset (scored by the Decision Index kit's own scorer)
against the mean request completion time, Callo's thinking budgets as two-point lines beside dedicated decision models
(Clef, d1-3B) as single markers, the five area skills as small multiples, and a table. A line's other arms at its think
budget (a plain think beside an early-exit point, a gated variant) are rows of the table, not drawn. The README's chart
(`di-chart-*`) is the same plot alone, under one title. Every number is the benchmark harness's DI tools' own:
`di_bootstrap.py` (paired resamples of linked groups with the Decision Index kit's `score_run_v02` in the loop; its
identity draw is asserted equal to the unresampled score; a second run with another reference pairs an early-exit point
with its plain think), `di_union.py` (the rows not answered by every arm), `di_patch.py`'s re-read records and each
arm's `di_meta.json`. `di.py build` re-hashes the results each bootstrap scored (a stale bootstrap is refused), checks
each arm's model file, think budget and early exit against its label, and refuses an arm with pending rows or an error
row of unknown cause; `di.py draw` refuses it again from the snapshot.
"""

CONC_METHOD = """## The companion figure (`concurrency.py`)

Decisions while an agent shares the GPU, from existing results only. The benchmark harness's
`extract_concurrency.py` records every number with its source file and JSON pointer; `concurrency.py build` re-reads
each one under `--root` and refuses a number that does not round-trip.
"""


def _md(s: str) -> str:
    """Markdown-safe text: `<|im_end|>`-style delimiters would otherwise be read as HTML tags and vanish."""
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _items(entries: list[dict]) -> str:
    return "\n".join(f"- **{_md(e['lead'])}** {_md(e['text'])}" if e.get("lead") else f"- {_md(e['text'])}"
                     for e in entries) + "\n"


def _drawn_tag(p: dict) -> str:
    """A DI arm's row tag: " (not drawn)" for a data-only arm, " (table only)" for a line's other arm at its think
    budget (a row of the plate's table, not drawn), nothing for a drawn point."""
    if not p.get("on_plate", True):
        return " (not drawn)"
    return " (table only)" if p.get("variant_of") else ""


def _di_table(t: dict, snap: dict) -> str:
    """One treatment's numbers, every plotted arm: index, the paired Δ vs both references, the area skills, latency."""
    import di
    areas = snap["areas"]
    head = (["Arm", "Index [95 % CI]", f"Δ vs {snap['reference']['label']} [95 % CI]",
             f"Δ vs {snap['second_reference']['label']} [95 % CI]"] + [a["label"] for a in areas]
            + ["Mean request time [95 % CI]", "p95"])
    rows = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for p in snap["points"]:
        a = t["arms"][p["arm"]]
        rows.append("| " + " | ".join(
            [_md(p["label"]) + _drawn_tag(p), f"{a['index']:.2f} {di.ci1(*a['index_ci'])}",
             di._dtxt(a["dref"]) if a["dref"] else "reference", di._dtxt(a["dsecond"]) if a["dsecond"] else "reference"]
            + [f"{di.f1(di.skill(a['areas'][x['id']]))} {di.ci1(*(di.skill(v) for v in a['areas_ci'][x['id']]))}"
               for x in areas]
            + [f"{di.secs(a['lat']['mean'])} [{di.secs(a['lat']['mean_ci'][0])}, {di.secs(a['lat']['mean_ci'][1])}]",
               di.secs(a["lat"]["p95"])]) + " |")
    return "\n".join(rows) + "\n"


def render_di(snap: dict) -> list[str]:
    g = snap.get("generator") or {}
    w = snap["wide"]
    out = [DI_METHOD, f"This bake: {'PRELIMINARY, ' if snap.get('preliminary') else ''}built {g.get('built')}; "
           f"Decision Index {snap['edition']}, kit {snap['kit_commit']}; "
           f"{snap['bootstrap']['n']} paired resamples, seed {snap['bootstrap']['seed']}; plotted: treatment "
           f"{w['label']} (`wide_options: {w['switch']}`).\n",
           f"### Both treatments of the > 26-option rows\n\n{w['rows_gt26']} rows ({', '.join(f'{n} {k}' for n, k in w['benchmarks'])}) "
           f"have more than 26 options, {w['rows_gt255']} more than 255. Index on its 0-100 scale (two decimals, "
           "as the Decision Index kit reports it); area skills ×100; Δ in index points.\n"]
    for key, t in snap["treatments"].items():
        mark = " (plotted)" if key == w["switch"] else ""
        if t.get("computed"):
            out += [f"**Treatment {_md(t['label'])}{mark}.** Source `{Path(t['path']).name}` (sha256 "
                    f"{t['sha256'][:16]}…).\n", _di_table(t, snap)]
        else:
            why = (t.get("why") or "not computed for this bake").rstrip(".")
            out.append(f"**Treatment {_md(t['label'])}{mark}.** {_md(why)}.\n")
    if snap.get("sensitivity"):
        out += [f"### Without {snap['sensitivity']['drop']}\n\nThe sensitivity footnote's numbers, per arm (index and "
                "paired Δ in index points at two decimals, as the Decision Index kit reports them, 95 % CIs; latency is "
                "the plotted bootstrap's).\n", _sens_table(snap)]
    inputs = [(f.get("role") or "input", f) for f in snap.get("inputs") or []]
    inputs += [(p["label"], f) for p in snap["points"] for f in p["provenance"]["files"]]
    out += [_items(snap.get("made") or []), "Inputs (sha256):\n",
            "\n".join(f"- {_md(who)}: `{Path(f['path']).name}` {f['sha256'][:16]}…" for who, f in inputs) + "\n"]
    return out


def _d2(d: list[float] | None) -> str:
    """A paired Δ with its CI at the kit's two decimals (a bound near 0 keeps its side), true minus signs."""
    if d is None:
        return "reference"
    return f"{d[0]:+.2f} [{d[1]:+.2f}, {d[2]:+.2f}]".replace("-", "−")


def _sens_table(snap: dict) -> str:
    s = snap["sensitivity"]
    ref, second = snap["reference"]["label"], snap["second_reference"]["label"]
    head = ["Arm", "Index", f"Without {s['drop']} [95 % CI]", f"Δ vs {ref}", "without", f"Δ vs {second}", "without"]
    rows = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for p in snap["points"]:
        a = s["arms"][p["arm"]]
        rows.append("| " + " | ".join([
            _md(p["label"]) + _drawn_tag(p), f"{a['with']:.2f}",
            f"{a['without']:.2f} [{a['without_ci'][0]:.2f}, {a['without_ci'][1]:.2f}]",
            _d2(a["dref"]), _d2(a["dref_without"]), _d2(a["dsecond"]), _d2(a["dsecond_without"])]) + " |")
    return "\n".join(rows) + "\n"


def _frontier_table(snap: dict) -> str:
    """Every point of the frontier snapshot, plotted or not: accuracy, the paired Δ vs the reference, the latency
    statistics, GiB and whether it is on its own model's frontier (on the mean)."""
    import frontier
    ref = (snap.get("ref") or {}).get("label") or "the reference"
    arms = {a["name"]: a for a in snap["arms"]}
    head = ["Point", "Accuracy", f"Δ vs {ref} [95 % CI]", "Mean [95 % CI]", "p50", "p95", "p99", "GiB", "Frontier (mean)"]
    rows = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for p in snap["points"]:
        a = arms[p["arm"]]
        name = a["label"] + ("" if a["kind"] != "callo" else " · " + ("no think" if not p["budget"]
                                                                        else f"think {p['budget']}"))
        d = p.get("dacc")
        dtxt = (f"{frontier._pp(d[0])} pp [{frontier._pp(d[1])}, {frontier._pp(d[2])}]" if d else "reference")
        m = p["lat"]["mean"]
        rows.append("| " + " | ".join([
            _md(name) + ("" if a.get("on_plate", True) else " (not drawn)"), f"{100 * p['acc']:.1f} %", dtxt,
            f"{frontier.secs(m[0])} [{frontier.secs(m[1])}, {frontier.secs(m[2])}]", frontier.secs(p["lat"]["p50"][0]),
            frontier.secs(p["lat"]["p95"][0]), frontier.secs(p["lat"]["p99"][0]),
            f"{p['gib']:.1f}" if p.get("gib") is not None else "–",
            "yes" if p["frontier"]["mean"] else f"no ({p['dominated_by']['mean']})"]) + " |")
    return "\n".join(rows) + "\n"


def render(frontier: dict | None, concurrency: dict | None, di: dict | None = None) -> str:
    out = [INTRO]
    if frontier is not None:
        g = frontier.get("generator") or {}
        extra = [x for x in ((frontier.get("early_exit") or {}).get("points") or []) if not x.get("own")]
        rc = frontier.get("readout_check")
        inputs = [(a["label"], f) for a in frontier["arms"] if a["status"] == "present" for f in a.get("files") or []]
        inputs += [(f"{x['short']}, early-exit calibration", {"path": x["path"], "sha256": x["sha256"]}) for x in extra]
        inputs += [(f"{rc['short']}, before the readout fix", {"path": rc["before"], "sha256": rc["sha256"]})] if rc else []
        v = frontier.get("validation") or {}
        inputs += [("Validation", {"path": v["path"], "sha256": v["sha256"]})] if v.get("path") else []
        out += [PLATE_METHOD, f"This bake: {'DRAFT, ' if frontier.get('draft') else ''}built {g.get('built')}; data "
                f"{frontier['data']['name']} (sha256 "
                f"{frontier['data']['sha256'][:16]}…), n = {frontier['data']['n']}.\n",
                _items(frontier.get("made") or []),
                "Every point (accuracy and paired Δ in percentage points; latency per decision):\n",
                _frontier_table(frontier),
                "Inputs (sha256):\n",
                "\n".join(f"- {_md(who)}: `{Path(f['path']).name}` {f['sha256'][:16]}…" for who, f in inputs) + "\n"]
    if concurrency is not None:
        out += [CONC_METHOD, f"This bake: {concurrency['verified_numbers']} numbers verified against "
                f"{len(concurrency.get('sources') or [])} source files.\n", _items(concurrency.get("made") or [])]
    if di is not None:
        out += render_di(di)
    out += render_builds([("frontier", frontier), ("concurrency", concurrency), ("di", di)])
    return "\n".join(out)


BUILDS_HEAD = """## Development builds

The figures and this page name Callo's builds by role. The commits below are commits of Callo's development history,
which is not published: they do not resolve in this repository and are listed here once, as provenance.
"""

GENERATORS = {"frontier": "`frontier.py build`", "concurrency": "`concurrency.py build`", "di": "`di.py build`"}


def render_builds(snaps: list[tuple[str, dict | None]]) -> list[str]:
    """The builds the snapshots name (data/builds.json, in the order they were made) and the commit each snapshot was
    built at: the one place their commits appear."""
    import figkit
    used = {b["commit"] for _, s in snaps if s for b in s.get("builds") or []}
    rows = [(b["name"], b["what"], b["commit"]) for b in figkit.builds() if b["commit"] in used]
    gens: dict[str, list[str]] = {}
    for key, s in snaps:
        c = ((s or {}).get("generator") or {}).get("callo_commit")
        if c:
            gens.setdefault(c, []).append(GENERATORS[key])
    rows += [(" and ".join(ks), "the commit the snapshot" + ("s were" if len(ks) > 1 else " was") + " built at", c)
             for c, ks in gens.items()]
    if not rows:
        return []
    table = ["| Name | What it is | Commit (development history) |", "|---|---|---|"]
    table += [f"| {_md(n)} | {_md(w)} | `{c}` |" for n, w, c in rows]
    return [BUILDS_HEAD, "\n".join(table) + "\n"]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--frontier", default=str(HERE / "data" / "frontier.json"))
    ap.add_argument("--concurrency", default=str(HERE / "data" / "concurrency.json"))
    ap.add_argument("--di", default=str(HERE / "data" / "di.json"))
    ap.add_argument("--out", default=str(HERE / "FIGURES.md"))
    a = ap.parse_args(argv)

    def load(p: str) -> dict | None:
        return json.loads(Path(p).read_text(encoding="utf-8")) if Path(p).is_file() else None

    Path(a.out).write_text(render(load(a.frontier), load(a.concurrency), load(a.di)), encoding="utf-8")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
